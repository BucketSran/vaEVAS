"""Resolve a previously calibrated Q target before generating simulator inputs.

The registry applies only to the eight frozen fixtures and exact tool identities.
It is not an a-priori accuracy guarantee for an arbitrary Verilog-A model.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[3]
DEFAULT_REGISTRY = Path(__file__).with_name('precision-bindings-v1.json')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_registry(path=DEFAULT_REGISTRY):
    value = json.loads(Path(path).read_text())
    if value.get('schema_version') != 1 or value.get('id') != 'precision-bindings-v1':
        raise ValueError('unknown binding contract')
    for name, expected in value['dependencies'].items():
        file = (ROOT / name).resolve()
        if not file.is_relative_to(ROOT) or digest(file) != expected:
            raise ValueError('binding dependency changed; recalibration required: ' + name)
    return value


def freeze_registry(analysis, receipt_path, registry_path):
    """Freeze a reviewed analysis without replacing earlier receipts or registries."""
    analysis, receipt_path, registry_path = map(Path, (analysis, receipt_path, registry_path))
    registry = load_registry(analysis / 'registry-draft.json')
    receipt = json.loads((analysis / 'receipt.json').read_text())
    if not registry['dependencies'] or registry['dependencies'] != receipt['analysis_dependencies']:
        raise ValueError('missing or inconsistent analysis dependencies')
    results = {r['id']: r for r in receipt['results']}
    for key, binding in registry['bindings'].items():
        if binding['status'] == 'qualified':
            selected = results[binding['configuration']]
            if selected['axes'][key.split('/')[-1]]['status'] != 'pass':
                raise ValueError('selected calibration did not pass')
    if receipt_path.exists() or registry_path.exists():
        raise ValueError('freeze requires new output paths')
    receipt_name = str(receipt_path.resolve().relative_to(ROOT))
    # Copy bytes so the frozen receipt is identical to the reviewed analysis.
    with receipt_path.open('xb') as target:
        target.write((analysis / 'receipt.json').read_bytes())
    registry['dependencies'][receipt_name] = digest(receipt_path)
    registry['calibration_receipt'] = receipt_name
    with registry_path.open('x') as target:
        json.dump(registry, target, indent=2, ensure_ascii=False, allow_nan=False)
        target.write('\n')
    return registry


def resolve(registry, tier, backend, condition, *, tool_identity=None):
    if tier not in ('Q1', 'Q2', 'Q3'): raise ValueError('unknown target tier')
    key = '/'.join((condition, backend, tier))
    if key not in registry['bindings']: raise ValueError('condition/backend outside calibrated scope')
    binding = registry['bindings'][key]
    if binding['status'] != 'qualified':
        return {'status': 'unavailable', 'tier': tier, 'backend': backend, 'condition': condition,
                'reasons': binding['reasons'], 'requirements': binding['requirements']}
    config = registry['configurations'][binding['configuration']]
    if tool_identity is not None and tool_identity != config['tool_identity']:
        raise ValueError('tool identity changed; calibration is not transferable')
    return {'status': 'qualified', 'tier': tier, 'backend': backend, 'condition': condition,
            'configuration': binding['configuration'], 'requirements': binding['requirements'],
            'settings': config['settings'], 'actual': config['actual'],
            'mapped_controls': config.get('mapped_controls'),
            'tool_identity': config['tool_identity'], 'recipe_hashes': config['recipe_hashes'],
            'callback_trace': config['callback_trace'], 'evidence': config['evidence'],
            'claim': 'calibrated finite observations of this frozen fixture; reruns must pass the checker'}


def prepare(registry, tier, backend, condition, output, tool_identity):
    """Require the current tool identity, then emit the exact calibrated recipe."""
    selected = resolve(registry, tier, backend, condition, tool_identity=tool_identity)
    if selected['status'] != 'qualified': raise ValueError('no qualified binding: ' + '; '.join(selected['reasons']))
    sys.path.insert(0, str(ROOT / 'experiments/backends/support'))
    from precision_binding_run import recipe, write_recipe
    from precision_v2 import load_contract
    card = next(c for c in load_contract()['cards'] if c['id'] == condition)
    files = recipe(card, selected['settings'], backend, callback_trace=selected['callback_trace'])
    output = Path(output)
    # Validate all generated bytes before creating a runnable directory.
    def serialized(value):
        return value if isinstance(value, str) else json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + '\n'
    for name, value in files.items():
        if hashlib.sha256(serialized(value).encode()).hexdigest() != selected['recipe_hashes'].get(name):
            raise ValueError('generated recipe differs from calibrated input: ' + name)
    write_recipe(output, files)
    (output / 'BINDING.json').write_text(json.dumps(selected, indent=2, ensure_ascii=False, allow_nan=False) + '\n')
    return selected


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument('--tier', choices=('Q1', 'Q2', 'Q3'))
    mode.add_argument('--freeze-analysis', type=Path, help='freeze after calibration and review')
    p.add_argument('--receipt', type=Path, help='new retained receipt path for freezing')
    p.add_argument('--backend'); p.add_argument('--condition')
    p.add_argument('--registry', type=Path, default=DEFAULT_REGISTRY)
    p.add_argument('--output', type=Path)
    p.add_argument('--tool-identity', type=Path, help='current normalized tool identity, mandatory for preparation')
    a = p.parse_args()
    if a.freeze_analysis:
        if not a.receipt: p.error('freezing requires --receipt and a new --registry path')
        freeze_registry(a.freeze_analysis, a.receipt, a.registry)
        print('Frozen', a.registry)
        sys.exit(0)
    registry = load_registry(a.registry)
    if a.output:
        if not (a.backend and a.condition and a.tool_identity):
            p.error('preparation requires backend, condition and current tool identity')
        answer = prepare(registry, a.tier, a.backend, a.condition, a.output, json.loads(a.tool_identity.read_text()))
    else:
        answer = [resolve(registry, a.tier, b, c) for c in registry['conditions'] for b in registry['backends']
                  if (a.condition is None or c == a.condition) and (a.backend is None or b == a.backend)]
        if not answer: p.error('no matching calibrated condition/backend')
    print(json.dumps(answer, indent=2, ensure_ascii=False, allow_nan=False))
