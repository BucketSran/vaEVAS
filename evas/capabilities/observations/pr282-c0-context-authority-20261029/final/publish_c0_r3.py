"""Publish the #282 C0 authority rebuilt on main b4a07295 (main session only; not run by the registration worker).

One atomic fast-forward push from the round-3 private repository flow/c0-r3/source/.git:
  - the publication archive (child of the construction archive, which merges the archive tip 18a202cb and the reused
    bundle commit 2b2569c4) to refs/heads/codex/evas-method-audit-archive-20261025, a fast-forward from 18a202cb, so the
    bundle the pointer names becomes public in the same push;
  - the C0 head to refs/heads/codex/pr4-context-authority, a fast-forward from the merged PR6 C0 head 6e3801a2.
Then the PR. No force push.
Generated by r2/make_r3_publish_scripts.py; not run by the registration worker.
Template: ../publish_c0.py (round 1) via publish_c0_r2.py. Differences: round-3 directory and constants; remote refs read with gh api before
and after; the governance receipt must record merge_allowed under main's production modules; precheck and inventory of
the same head must be green.
Usage: python3 -B publish_c0_r3.py
"""
import re
import shutil
import subprocess

from common_r3 import *

spec = importlib.util.spec_from_file_location('flow_prepare_c0_r3_for_publish', R2 / 'prepare_c0_r3.py')
c = importlib.util.module_from_spec(spec)
spec.loader.exec_module(c)
D, S = c.D, c.S
BRANCH = 'refs/heads/codex/pr4-context-authority'
PRIOR = '6e3801a2dc54771b831ba68ed0ae752287149a7d'
PUB_PREFIX = c.PREFIX_C0 + '/final'
TITLE = 'Authorize the exact capability batch 1 observation context'


def gh(*args):
    return subprocess.check_output(['gh', *args], env=clean_env())


def remote_ref(ref):
    return json.loads(gh('api', 'repos/' + REPO + '/git/ref/' + ref.removeprefix('refs/')))['object']['sha']


def publication_archive(construction):
    if (D / 'publication-archive.json').exists():
        return load(D / 'publication-archive.json')
    dest = D / 'archive-final-files' / PUB_PREFIX
    dest.mkdir(parents=True)
    write_r3(D / 'candidate.patch.identity.json', {'base': c.BASE, 'head': load(D / 'final-candidate.json')['commit'],
             'command': 'git diff --binary <base> <head>', 'sha256': sha_file(D / 'candidate.patch')[0]})
    for name in ('final-candidate.json', 'derive-acceptance.json', 'generation-acceptance.json', 'candidate.patch.identity.json',
                 'precheck-acceptance.json', 'inventory-acceptance.json'):
        shutil.copyfile(D / name, dest / name)
    for path in (R2 / 'prepare_c0_r3.py', R2 / 'common_r3.py', R2 / 'publish_c0_r3.py'):
        shutil.copyfile(path, dest / path.name)
    index = R2 / 'indexes' / 'r3-publication-archive.index'
    assert not index.exists()
    pgit(S, 'read-tree', construction['commit'], index=index)
    files = []
    root = D / 'archive-final-files'
    for p in sorted(root.rglob('*')):
        if not p.is_file():
            continue
        raw = p.read_bytes()
        assert len(raw) < c.WARNING_BYTES, (p, len(raw))
        rel = p.relative_to(root).as_posix()
        oid = pgit(S, 'hash-object', '-w', '--stdin', data=raw).decode().strip()
        pgit(S, 'update-index', '--add', '--cacheinfo', '100644,' + oid + ',' + rel, index=index)
        files.append({'path': rel, 'sha256': sha(raw), 'bytes': len(raw)})
    tree = pgit(S, 'write-tree', index=index).decode().strip()
    commit = pgit(S, 'commit-tree', tree, '-p', construction['commit'], '-m', 'Archive the capability batch 1 C0 authority receipts' + TRAILER).decode().strip()
    index.unlink()
    result = {'parent': construction['commit'], 'commit': commit, 'tree': tree, 'prefix': PUB_PREFIX, 'files': files, 'published': False}
    write_r3(D / 'publication-archive.json', result)
    return result


def main():
    before_guard = guard_record_r2('publish-c0-r3-before')['observed_at']
    assert not (D / 'publication-start.json').exists(), 'Inspect actual refs before resuming any prior publication attempt'
    gov = load(D / 'governance-draft/receipt.json')
    assert load(D / 'catalog-gate.json')['ok'] and load(D / 'catalog-end-gate.json')['ok']
    assert gov['production_validation']['merge_allowed'] and gov['production_validation']['revision'] == c.BASE, gov['production_validation']
    final, der, cap = load(D / 'final-candidate.json'), load(D / 'derive-acceptance.json'), load(D / 'capture.json')
    pre, inv = load(D / 'precheck-acceptance.json'), load(D / 'inventory-acceptance.json')
    assert pre['candidate'] == inv['candidate'] == final['commit'] and not pre['failures']
    construction, bundle = load(D / 'archive.json'), load(D / 'bundle-archive.json')
    assert construction['parents'] == [c.ARCHIVE_TIP, c.BUNDLE_ARCHIVE], construction['parents']
    assert all(row['returncode'] == 0 for row in der['checks'])
    assert all(sha_file(S / p)[0] == value for p, value in der['files'].items())
    assert pgit(S, 'rev-parse', 'HEAD').decode().strip() == final['commit']
    assert pgit(S, 'rev-parse', final['commit'] + '^').decode().strip() == cap['commit']
    assert pgit(S, 'rev-parse', cap['commit'] + '^').decode().strip() == c.BASE
    pointer = json.loads((S / POINTER_PATH).read_text())
    assert pointer == bundle['pointer'] and pointer['commit'] == bundle['commit']
    archive = publication_archive(construction)
    for anc in (c.ARCHIVE_TIP, bundle['commit'], construction['commit']):
        pgit(S, 'merge-base', '--is-ancestor', anc, archive['commit'])
    pgit(S, 'merge-base', '--is-ancestor', PRIOR, final['commit'])
    pgit(S, 'merge-base', '--is-ancestor', c.BASE, final['commit'])
    refs = [BRANCH, c.ARCHIVE_REF, 'refs/heads/main']
    before = {ref: remote_ref(ref) for ref in refs}
    assert before == {BRANCH: PRIOR, c.ARCHIVE_REF: c.ARCHIVE_TIP, 'refs/heads/main': c.BASE}, before
    open_prs = json.loads(gh('pr', 'list', '--repo', REPO, '--head', BRANCH.removeprefix('refs/heads/'), '--state', 'open', '--json', 'number,url,headRefOid'))
    assert open_prs == [], open_prs
    production = gov['production_validation']
    generation = load(D / 'generation-acceptance.json')
    values = {'{HEAD}': final['commit'], '{TREE}': final['tree'], '{BASE}': c.BASE, '{BUNDLE_SHORT}': bundle['commit'][:8],
              '{EVIDENCE}': REPO_URL + '/tree/' + archive['commit'] + '/' + c.PREFIX_C0,
              '{BUNDLE_URL}': REPO_URL + '/tree/' + bundle['commit'] + '/' + c.PREFIX_BUNDLE,
              '{ENTRY_DIGEST}': gov['entry_canonical_sha256'], '{PREVIOUS_CONTEXT}': gov['previous_context_sha256'],
              '{REGISTRATION_RESULT}': 'returns `valid`, `merge_allowed` and `transition.registration` with no differences',
              '{NEGATIVES}': str(gov['negative_controls']), '{OLD_VERSIONS}': format(generation['old_versions_retained'], ','),
              '{NEW_VERSIONS}': format(generation['new_object_versions'], ',')}
    body = (R2 / 'pr-body-r3.md').read_text()
    for token, value in values.items():
        assert token in body, token
        body = body.replace(token, value)
    assert not re.search(r'\{[A-Z_]+\}', body)
    write_r3(D / 'pr-body.final.md', body.encode())
    write_r3(D / 'publication-start.json', {'started_at_utc': utc(), 'candidate': final['commit'], 'tree': final['tree'], 'archive': archive['commit'],
             'refs_before': before, 'force_push': False})
    argv = [GIT, '--git-dir=' + str(S / '.git'), 'push', '--atomic', '--porcelain', REPO_URL + '.git',
            final['commit'] + ':' + BRANCH, archive['commit'] + ':' + c.ARCHIVE_REF]
    with (D / 'push.stdout').open('xb') as out, (D / 'push.stderr').open('xb') as err:
        run = subprocess.run(argv, env=clean_env(), stdout=out, stderr=err)
    assert run.returncode == 0, 'Inspect retained push output and actual refs; do not blindly repeat'
    after = {ref: remote_ref(ref) for ref in refs}
    assert after == {BRANCH: final['commit'], c.ARCHIVE_REF: archive['commit'], 'refs/heads/main': c.BASE}, after
    with (D / 'pr-create.stdout').open('xb') as out, (D / 'pr-create.stderr').open('xb') as err:
        made = subprocess.run(['gh', 'pr', 'create', '--repo', REPO, '--base', 'main', '--head', BRANCH.removeprefix('refs/heads/'),
                               '--title', TITLE, '--body-file', str(D / 'pr-body.final.md')], env=clean_env(), stdout=out, stderr=err)
    assert made.returncode == 0, 'Read pr-create.stderr'
    url = (D / 'pr-create.stdout').read_text().strip().splitlines()[-1]
    assert re.fullmatch(r'https://github.com/BucketSran/vaEVAS/pull/\d+', url), url
    view = json.loads(gh('pr', 'view', url, '--repo', REPO, '--json', 'state,headRefOid,baseRefName,body,title,number'))
    assert view['state'] == 'OPEN' and view['headRefOid'] == final['commit'] and view['baseRefName'] == 'main'
    assert view['body'].replace('\r\n', '\n').strip() == body.strip()
    write_r3(D / 'publication.json', {'published_at_utc': utc(), 'PR': url, 'number': view['number'], 'title': TITLE,
             'candidate': final['commit'], 'tree': final['tree'], 'base': c.BASE, 'bundle_archive': bundle['commit'],
             'construction_archive': construction['commit'], 'publication_archive': archive['commit'], 'refs_before': before, 'refs_after': after,
             'body_sha256': sha(body.encode()), 'pushed': True, 'force_push': False, 'independent_review': 'pending', 'necessary_CI': 'pending',
             'merged': False, 'guard_before': before_guard, 'guard_after': guard_record_r2('publish-c0-r3-after')['observed_at'],
             'scientific_qualification': False})
    print(json.dumps({'PR': url, 'head': final['commit'], 'archive': archive['commit'], 'published': True,
                      'action_required': 'link_pull_request and watch this PR in T3'}), flush=True)


if __name__ == '__main__':
    main()
