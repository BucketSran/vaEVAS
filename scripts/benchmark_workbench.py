SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")
CASE_ID = re.compile(r"case-[0-9]{4,}\Z")
GENERATED = "<!-- Generated by scripts/benchmark_workbench.py; edit case.json or the source pages. -->\n"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def link(label, target, page):
    relative = os.path.relpath(target, page.parent)
    return f"[{cell(label)}]({quote(relative, safe='/.-_')})"


def table(headers, rows):
    return "\n".join([
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
        *("| " + " | ".join(row) + " |" for row in rows),
    ]) + "\n"


def replace_block(path, block, tag="workbench", original=None):
    if original is None:
        original = path.read_text(encoding="utf-8")
    begin, end = f"<!-- {tag}:begin -->", f"<!-- {tag}:end -->"
    require(original.count(begin) == original.count(end) == 1,
            f"{path}: expected exactly one {tag} marker pair")
    start = original.index(begin) + len(begin)
    stop = original.index(end)
    require(start < stop, f"{path}: reversed {tag} markers")
    return original[:start] + "\n\n" + block.rstrip() + "\n\n" + original[stop:]


def repository_file(repo, value, field):
    require(isinstance(value, str) and value, f"{field}: expected repository-relative path")
    path = Path(value)
    require(not path.is_absolute(), f"{field}: absolute path is not portable")
    target = (repo / path).resolve()
    require(target.is_relative_to(repo.resolve()), f"{field}: path escapes repository")
    require(target.exists(), f"{field}: missing path {value}")
    return target


def load_catalog(root):
    catalog = read_json(root / "catalog.json")
    require(isinstance(catalog, dict), "catalog.json: expected object")
    for section in ("categories", "families"):
        entries = catalog.get(section)
        require(isinstance(entries, dict) and entries, f"catalog.json: missing {section}")
        for key, label in entries.items():
            require(SLUG.fullmatch(key) and isinstance(label, str) and label.strip(),
                    f"catalog.json: invalid {section} entry {key}")
    return catalog


def load_cases(root, catalog):
    cases = []
    ids = set()
    repo = root.parents[2]
    for path in sorted((root / "cases").rglob("case.json")):
        data = read_json(path)
        require(isinstance(data, dict), f"{path}: expected object")
        identity = data.get("case_id", "")
        require(isinstance(identity, str) and CASE_ID.fullmatch(identity), f"{path}: invalid case_id")
        require(identity not in ids, f"duplicate case_id: {identity}")
        ids.add(identity)
        for field in ("title", "review_focus", "proposed_form"):
            require(isinstance(data.get(field), str) and data[field].strip(), f"{identity}: missing {field}")
        action, family = data.get("engineering_action"), data.get("circuit_family")
        require(action in catalog["categories"], f"{identity}: unknown engineering_action")
        require(family in catalog["families"], f"{identity}: unknown circuit_family")
        require(path.parent.parent == root / "cases" / action / family
                and path.parent.name.startswith(identity + "-"),
                f"{identity}: directory must match category, family and case_id")
        for field, allowed in (("stage", STAGES), ("review_status", REVIEWS),
                               ("context_level", CONTEXTS), ("public_test_mode", MODES)):
            require(data.get(field) in allowed, f"{identity}: invalid {field}")
        revision = data.get("design_revision")
        require(type(revision) is int and revision >= 1, f"{identity}: invalid design_revision")
        reviewed = data.get("reviewed_revision")
        require(reviewed is None or (type(reviewed) is int and 1 <= reviewed <= revision),
                f"{identity}: invalid reviewed_revision")
        if data["review_status"] == "accepted":
            require(reviewed == revision, f"{identity}: accepted review requires current reviewed_revision")
        for field in ("source_ids", "circuit_ids", "source_groups", "subtypes", "evidence_paths"):
            entries = data.get(field)
            require(isinstance(entries, list) and all(isinstance(v, str) and v.strip() for v in entries),
                    f"{identity}: invalid {field}")
            require(len(entries) == len(set(entries)), f"{identity}: duplicate {field}")
        for field, directory in (("source_ids", "sources"), ("circuit_ids", "circuits")):
            for entry in data[field]:
                require(SLUG.fullmatch(entry), f"{identity}: invalid {field} identifier")
                require((root / directory / f"{entry}.md").is_file(),
                        f"{identity}: missing {field} target {entry}")
        require(all(SLUG.fullmatch(v) for v in data["source_groups"]), f"{identity}: invalid source_groups")
        for entry in data["evidence_paths"]:
            repository_file(repo, entry, f"{identity}.evidence_paths")
        if data.get("task_path") is not None:
            repository_file(repo, data["task_path"], f"{identity}.task_path")
        require(data.get("backend") is None or (isinstance(data["backend"], str) and data["backend"].strip()),
                f"{identity}: backend must be null or a toolchain description")
        relations = data.get("related_cases")
        require(isinstance(relations, list), f"{identity}: invalid related_cases")
        for relation in relations:
            require(isinstance(relation, dict) and isinstance(relation.get("case_id"), str)
                    and relation.get("relation") in {"derived-from", "simplified-from", "related"},
                    f"{identity}: invalid related_cases entry")
        data["directory"] = path.parent
        cases.append(data)
    for data in cases:
        for relation in data["related_cases"]:
            require(relation["case_id"] in ids and relation["case_id"] != data["case_id"],
                    f"{data['case_id']}: dangling or self related_cases reference {relation['case_id']}")
    return sorted(cases, key=lambda data: int(data["case_id"].split("-")[1]))


def task_batch(identity):
    match = re.match(r"v([0-9]+)-", identity)
    return f"v{match[1]}" if match and int(match[1]) >= 2 else None


def batch_packages(root):
    """Locate real packages in batches; one task has only one active draft."""
    require(not (root / "tasks").exists(), "flat draftbench/tasks is obsolete; use batches/<batch>/tasks")
    packages = {}
    for batch in sorted((root / "batches").iterdir()) if (root / "batches").exists() else []:
        if not batch.is_dir():
            continue
        require(SLUG.fullmatch(batch.name), f"invalid batch directory: {batch.name}")
        require((batch / "README.md").is_file(), f"{batch.name}: missing batch README")
        for task in sorted((batch / "tasks").iterdir()) if (batch / "tasks").exists() else []:
            if not task.is_dir():
                continue
            require(task.name not in packages, f"duplicate draft task across batches: {task.name}")
            packages[task.name] = task
    return packages


def load_tasks(root, catalog, cases):
    """Read source/category facts from task files, keeping only lineage in tasks.json."""
    data = read_json(root / "tasks.json")
    require(isinstance(data, dict) and set(data) == {"schema_version", "function_groups", "tasks"}
            and type(data["schema_version"]) is int and data["schema_version"] == 1,
            "tasks.json: invalid schema; review and execution status belong in their evidence records")
    groups = data["function_groups"]
    require(isinstance(groups, dict), "tasks.json: invalid function_groups")
    review_ids = set()
    for key, group in groups.items():
        require(SLUG.fullmatch(key) and isinstance(group, dict)
                and set(group) == {"title", "review_id"}
                and isinstance(group["title"], str) and group["title"].strip(),
                f"tasks.json: invalid function group {key}")
        review_id = group["review_id"]
        require(isinstance(review_id, str) and re.fullmatch(r"R[0-9]{2,}", review_id)
                and review_id not in review_ids, f"tasks.json: invalid or duplicate review_id {review_id}")
        review_ids.add(review_id)
    rows = data["tasks"]
    require(isinstance(rows, list), "tasks.json: tasks must be a list")
    case_index = {c["case_id"]: c for c in cases}
    tasks, ids = [], set()
    repo = root.parents[2]
    packages = batch_packages(root)
    formal_root = repo / "benchmark/tasks"
    formal = {p.name: p for p in formal_root.iterdir() if p.is_dir()} if formal_root.exists() else {}
    require(not (packages.keys() & formal.keys()), "task has both a draft and a formal package")
    for row in rows:
        require(isinstance(row, dict) and set(row) == {"task_id", "title", "function_group", "case_ids"},
                "tasks.json: invalid task fields; category and source_group come from task.toml")
        identity = row["task_id"]
        require(isinstance(identity, str) and SLUG.fullmatch(identity) and task_batch(identity),
                f"invalid task_id: {identity}")
        require(identity not in ids, f"duplicate task_id: {identity}")
        ids.add(identity)
        require(isinstance(row["title"], str) and row["title"].strip(), f"{identity}: missing title")
        require(isinstance(row["function_group"], str) and row["function_group"] in groups,
                f"{identity}: unknown function_group")
        linked = row["case_ids"]
        require(isinstance(linked, list) and all(isinstance(c, str) and c in case_index for c in linked)
                and len(linked) == len(set(linked)), f"{identity}: invalid case_ids")
        directory = packages.get(identity, formal.get(identity))
        require(directory is not None, f"{identity}: missing task package")
        for filename in ("instruction.md", "SOURCE.md", "task.toml"):
            target = repository_file(repo, str(directory.relative_to(repo) / filename), identity)
            require(target.is_file(), f"{identity}: expected file {filename}")
        metadata = tomllib.loads((directory / "task.toml").read_text(encoding="utf-8")).get("metadata", {})
        require(isinstance(metadata, dict), f"{identity}: invalid metadata table")
        require(metadata.get("name") == identity, f"{identity}: task.toml name mismatch")
        action, source = metadata.get("engineering_action"), metadata.get("source_group")
        require(isinstance(action, str) and action in catalog["categories"], f"{identity}: unknown engineering_action")
        require(isinstance(source, str) and source.strip(), f"{identity}: missing source_group")
        tasks.append(dict(row, directory=directory, batch=task_batch(identity),
                          engineering_action=action, source_group=source))
    discovered = {name for name in packages.keys() | formal.keys() if task_batch(name)}
    require(ids == discovered,
            f"task registration mismatch: unregistered={sorted(discovered - ids)}, missing={sorted(ids - discovered)}")
    for case in cases:
        if case["task_path"] is not None:
            target = (repo / case["task_path"]).resolve()
            if target in {p.resolve() for p in [*packages.values(), *formal.values()]} and task_batch(target.name):
                require(any(t["task_id"] == target.name and case["case_id"] in t["case_ids"] for t in tasks),
                        f"{case['case_id']}: task_path disagrees with tasks.json")
    return groups, tasks


def render_tasks(root, catalog, groups, tasks, cases, outputs):
    """Generate counts and navigation only; preserve human judgments and contracts."""
    categories = catalog["categories"]
    batches = sorted({t["batch"] for t in tasks}, key=lambda b: int(b[1:]))
    summary = f"登记 **{len(tasks)} 道待审核题包资产**；" + "、".join(
        f"{batch} {sum(t['batch'] == batch for t in tasks)} 道" for batch in batches) + "。\n"
    summary += "类别、来源组读自 `task.toml`；实现与历史作者校准不代表人工审核通过，正式题目仅见 `benchmark/tasks/benchmark.toml`。\n"
    for name in ("README.md", "TASKS.md"):
        page = root / name
        outputs[page] = replace_block(page, summary, "task-summary", outputs.get(page))
    page = root / "TASKS.md"
    counts = table(["工程动作", *batches, "合计"], [
        [label, *(str(sum(t["engineering_action"] == key and t["batch"] == batch for t in tasks)) for batch in batches),
         str(sum(t["engineering_action"] == key for t in tasks))] for key, label in categories.items()
    ] + [["总计", *(str(sum(t["batch"] == b for t in tasks)) for b in batches), str(len(tasks))]])
    functions = table(["审核组 / 电路功能", *categories.values(), "合计"], [
        [cell(group["review_id"] + " / " + group["title"]),
         *(str(sum(t["function_group"] == key and t["engineering_action"] == c for t in tasks)) for c in categories),
         str(sum(t["function_group"] == key for t in tasks))] for key, group in groups.items()
    ] + [["总计", *(str(sum(t["engineering_action"] == c for t in tasks)) for c in categories), str(len(tasks))]])
    case_index = {c["case_id"]: c for c in cases}
    index = table(["电路功能", "批次 / 类别", "任务与有效题面", "来源 / 元数据来源组", "历史设计卡"], [
        [cell(groups[t["function_group"]]["title"]), cell(t["batch"] + " / " + categories[t["engineering_action"]]),
         link(t["title"], t["directory"] / "instruction.md", page),
         link("SOURCE", t["directory"] / "SOURCE.md", page) + " / " + cell(t["source_group"]),
         "、".join(case_link(case_index[c], page) for c in t["case_ids"]) or "无历史卡"] for t in tasks
    ])
    for tag, block in (("task-category-counts", counts), ("task-function-counts", functions), ("task-inventory", index)):
        outputs[page] = replace_block(page, block, tag, outputs[page])


def case_link(data, page):
    return link(data["case_id"], data["directory"] / "README.md", page)


def case_table(cases, page, catalog):
    if not cases:
        return "尚未登记候选。\n"
    return table(["Case", "题目", "工程动作 / 电路家族", "阶段 / 设计 review", "本轮关注"], [
        [case_link(d, page), cell(d["title"]),
         cell(catalog["categories"][d["engineering_action"]] + " / " + catalog["families"][d["circuit_family"]]),
         cell(STAGES[d["stage"]] + " / " + REVIEWS[d["review_status"]] + f"（r{d['design_revision']}）"),
         cell(d["review_focus"])] for d in cases
    ])


def render(root, catalog, cases, groups, tasks):
    """Build all expected contents before writing anything, including marker validation."""
    outputs = {}
    page = root / "README.md"
    summary = f"登记 **{len(cases)} 张历史候选设计卡**；设计卡状态与题包实现分开维护，当前草稿见 [题包资产总览](TASKS.md)。\n\n"
    summary += table(["工程动作", "候选数"], [
        [link(label, root / "cases" / category / "README.md", page),
         str(sum(d["engineering_action"] == category for d in cases))]
        for category, label in catalog["categories"].items()
    ]) + "\n" + case_table(cases, page, catalog)
    outputs[page] = replace_block(page, summary)
    for category, label in catalog["categories"].items():
        selected = [d for d in cases if d["engineering_action"] == category]
        page = root / "cases" / category / "README.md"
        outputs[page] = GENERATED + f"# {label}\n\n" + link("工作区总览", root / "README.md", page) + "\n\n"
        outputs[page] += case_table(selected, page, catalog)
        for family in sorted({d["circuit_family"] for d in selected}):
            family_page = page.parent / family / "README.md"
            outputs[page] += "\n" + link(catalog["families"][family], family_page, page) + "\n"
            outputs[family_page] = GENERATED + f"# {label} / {catalog['families'][family]}\n\n"
            outputs[family_page] += link("工程动作索引", page, family_page) + "\n\n"
            outputs[family_page] += case_table([d for d in selected if d["circuit_family"] == family], family_page, catalog)
    for data in cases:
        page = data["directory"] / "README.md"
        rows = [
            ["Case / 设计版本", f"{data['case_id']} / r{data['design_revision']}"],
            ["工程动作 / 电路家族", cell(catalog["categories"][data["engineering_action"]] + " / " + catalog["families"][data["circuit_family"]])],
            ["细分 / 上下文规模", cell("、".join(data["subtypes"]) + " / " + CONTEXTS[data["context_level"]])],
            ["阶段 / 设计 review", cell(STAGES[data["stage"]] + " / " + REVIEWS[data["review_status"]])],
            ["已 review 的设计版本", f"r{data['reviewed_revision']}" if data["reviewed_revision"] else "无"],
            ["拟定形式", cell(data["proposed_form"])],
            ["公开自测形式", cell(MODES[data["public_test_mode"]])],
            ["固定后端", cell(data["backend"] or "待选定；尚无运行验证")],
            ["Review 关注", cell(data["review_focus"])],
        ]
        for field, directory, label in (("source_ids", "sources", "来源"), ("circuit_ids", "circuits", "电路资产")):
            rows.append([label, "、".join(link(v, root / directory / f"{v}.md", page) for v in data[field]) or "待选定"])
        rows.append(["同源组", cell("、".join(data["source_groups"]) or "未确定；不与其他未知项合并")])
        related = {d["case_id"]: d for d in cases}
        rows.append(["关联 Case", "、".join(case_link(related[r["case_id"]], page) + "（" + r["relation"] + "）" for r in data["related_cases"]) or "无"])
        linked_tasks = [t for t in tasks if data["case_id"] in t["case_ids"]]
        task_links = [link(t["task_id"], t["directory"] / "instruction.md", page) for t in linked_tasks]
        if data["task_path"] and not linked_tasks:
            task_links.append(link(data["task_path"], root.parents[2] / data["task_path"], page))
        rows.append(["关联的待审核题包资产", "、".join(task_links) or "尚无登记映射"])
        rows.append(["本卡登记的运行 / 校准证据", "、".join(link(v, root.parents[2] / v, page) for v in data["evidence_paths"])
                     or "本卡未登记；关联任务的校准范围见" + link("交付证据入口", root / "TASKS.md", page)])
        outputs[page] = replace_block(page, table(["项目", "当前记录"], rows))
    page = root / "REVIEW.md"
    outputs[page] = GENERATED + "# 设计 Review\n\n设计认可与实现、校准、任务冻结分别记录。这里只汇总历史设计卡的 review 状态；实现映射见 [题包资产总览](TASKS.md)。当前按电路类别的审核结论维护在 [#159](https://github.com/BucketSran/vaEVAS/issues/159)。pending 表示具体设计尚待审核，草稿登记不会改变设计认可。\n"
    for status, label in REVIEWS.items():
        outputs[page] += f"\n## {label}\n\n" + case_table([d for d in cases if d["review_status"] == status], page, catalog)
    page = root / "SOURCE_GROUPS.md"
    outputs[page] = GENERATED + "# 同源任务\n\n同一来源组中的题目保留独立 Case ID；分析成绩时考虑共享电路、数据或衍生关系。引用同一篇方法论文不自动归为同源。本页仅覆盖历史设计卡，题包资产的同源变体见 [题包资产总览](TASKS.md#同源变体与跨题关联)。\n"
    for group in sorted({v for d in cases for v in d["source_groups"]}):
        outputs[page] += f"\n## {group}\n\n" + case_table([d for d in cases if group in d["source_groups"]], page, catalog)
    outputs[page] += "\n## 尚未确定来源组\n\n以下各项不视为同一组。\n\n"
    outputs[page] += case_table([d for d in cases if not d["source_groups"]], page, catalog)
    for directory, field, title in (("sources", "source_ids", "材料来源"), ("circuits", "circuit_ids", "电路资产")):
        page = root / directory / "README.md"
        rows = []
        for source in sorted((root / directory).glob("*.md")):
            if source.name == "README.md":
                continue
            headings = [line[2:] for line in source.read_text(encoding="utf-8").splitlines() if line.startswith("# ")]
            rows.append([link(headings[0] if headings else source.stem, source, page),
                         "、".join(case_link(d, page) for d in cases if source.stem in d[field]) or "尚无 Case"])
        outputs[page] = GENERATED + f"# {title}\n\n" + table(["记录", "关联 Case"], rows)
    render_tasks(root, catalog, groups, tasks, cases, outputs)
    return outputs


def validate_formal_tasks(repo):
    """Keep unpublished designs out of the reviewed task collection."""
    root = repo / "benchmark/tasks"
    manifest = tomllib.loads((root / "benchmark.toml").read_text(encoding="utf-8"))
    require(manifest.get("schema_version") == 1, "benchmark.toml: unsupported schema")
    require(manifest.get("state") in {"draft", "frozen"}, "benchmark.toml: invalid state")
    require(manifest.get("task_defaults") == "defaults.toml", "benchmark.toml: missing defaults.toml")
    defaults = tomllib.loads((root / "defaults.toml").read_text(encoding="utf-8"))
    require(defaults.get("schema_version") == 1, "defaults.toml: unsupported schema")
    rows = manifest.get("tasks")
    require(isinstance(rows, list), "benchmark.toml: tasks must be a list")
    ids, slots = set(), set()
    for row in rows:
        require(isinstance(row, dict) and set(row) == {"slot", "id"}, "benchmark.toml: invalid task entry")
        identity, slot = row["id"], row["slot"]
        require(isinstance(identity, str) and SLUG.fullmatch(identity) and identity not in ids,
                "benchmark.toml: invalid or duplicate task id")
        require(type(slot) is int and slot > 0 and slot not in slots, "benchmark.toml: invalid or duplicate slot")
        ids.add(identity)
        slots.add(slot)
        task = root / identity
        for name in ("instruction.md", "task.toml", "SOURCE.md", "environment/Dockerfile",
                     "solution/solve.sh", "tests/test.sh", "tests/verify.py",
                     "results/reference.json", "results/calibration.json"):
            require((task / name).is_file(), f"{identity}: formal task missing {name}")
        metadata = tomllib.loads((task / "task.toml").read_text(encoding="utf-8")).get("metadata", {})
        require(metadata.get("review_status") == "accepted",
                f"{identity}: formal task requires explicit accepted review")
        validate_package(task, repo, formal=True)
    directories = {p.name for p in root.iterdir() if p.is_dir()}
    require(ids == directories,
            f"formal task collection mismatch: unlisted={sorted(directories - ids)}, missing={sorted(ids - directories)}")
    require(manifest["state"] != "frozen" or bool(rows), "benchmark.toml: empty collection cannot be frozen")
    return len(rows)


def validate_draft_packages(root, registered):
    """Retain registered v2/v3 compatibility; all other drafts use stage checks."""
    legacy_ids = legacy_task_ids(root.parents[2]) & {t["task_id"] for t in registered}
    counts = dict.fromkeys(LEVELS, 0)
    legacy = 0
    for identity, task in batch_packages(root).items():
        config = read_config(task)
        if (identity in legacy_ids and "stage" not in config["metadata"]
                and "artifacts" not in config and not (task / "environment/starter").exists()):
            legacy += 1
            continue
        level = validate_package(task, root.parents[2])
        counts[level] += 1
    return counts, legacy


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1] / "benchmark/material/draftbench")
    parser.add_argument("--package", type=Path, help="check one package without generating indexes")
    parser.add_argument("--stage", choices=LEVELS, help="require this check level or higher; --package only")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="check metadata and stale indexes without writing")
    mode.add_argument("--write", action="store_true", help="validate and refresh generated indexes")
    args = parser.parse_args()
    if (args.package and not args.check) or (args.stage and not args.package):
        parser.error("--package requires --check; --stage requires --package")
    try:
        root = args.root.resolve()
        if args.package:
            task = args.package.absolute()
            formal = task.parent.resolve() == root.parents[2] / "benchmark/tasks"
            level = validate_package(task, root.parents[2], level=args.stage, formal=formal)
            print(f"{task.name}: {level} static checks passed; simulation and calibration not executed; "
                  "human approval and evidence identity not verified")
            return 0
        formal_count = validate_formal_tasks(root.parents[2])
        catalog = load_catalog(root)
        cases = load_cases(root, catalog)
        groups, tasks = load_tasks(root, catalog, cases)
        levels, legacy_count = validate_draft_packages(root, tasks)
        outputs = render(root, catalog, cases, groups, tasks)
        for path, content in outputs.items():
            if content.startswith(GENERATED) and path.exists():
                require(path.read_text(encoding="utf-8").startswith(GENERATED),
                        f"{path}: refusing to overwrite unmarked human index")
        changed = [path for path, content in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != content]
        obsolete = [path for path in (root / "cases").rglob("README.md")
                    if path not in outputs and path.read_text(encoding="utf-8").startswith(GENERATED)]
        if args.check and (changed or obsolete):
            raise ValueError("stale generated views: " + ", ".join(str(p.relative_to(root)) for p in changed + obsolete))
        for path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(outputs[path], encoding="utf-8")
        for path in obsolete:
            path.unlink()
        print(f"{len(cases)} cases, {len(tasks)} draft assets and {formal_count} reviewed tasks validated; {len(changed)} views updated; {len(obsolete)} obsolete indexes removed"
              if args.write else f"{len(cases)} cases, {len(tasks)} draft assets and {formal_count} reviewed tasks validated; all generated views current")
        print("Draft package static checks: " + ", ".join(f"{name}={count}" for name, count in levels.items())
              + f"; legacy registration only={legacy_count}. Simulation and calibration not executed; "
                "human approval and evidence identity not verified.")
        return 0
    except (OSError, ValueError, TypeError, KeyError) as error:
        print(f"workbench: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
