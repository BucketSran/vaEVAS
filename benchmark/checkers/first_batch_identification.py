"""Independent observed-voltage criteria for identification tasks.

Expected probe values are authoring-time contracts, never generated by candidate
or reference VA code. Local metrics prevent quiet intervals hiding bad edges.
"""
import bisect
import math


def evaluate(rows, case, work=None):
    failures = []
    nodes={p.get("node","out") for p in case.get("probes",[])} | {m.get("node","out") for m in case.get("metrics",[])} | {e.get("node","out") for e in case.get("crossings",[])}
    if len(rows) < 2 or any(not ({"time"}|nodes) <= r.keys() for r in rows):
        return dict(passed=False, failures=["missing waveform"])
    times = [r["time"] for r in rows]
    if any(not math.isfinite(r[n]) for r in rows for n in ({"time"}|nodes)) or any(b <= a for a, b in zip(times, times[1:])):
        return dict(passed=False, failures=["nonfinite or non-increasing waveform"])

    def sample(t,node="out"):
        if t < times[0] or t > times[-1]:
            raise ValueError(f"observation {t} outside trace")
        j = max(0, min(bisect.bisect_right(times, t)-1, len(rows)-2))
        a, b = rows[j], rows[j+1]
        return a[node]+(b[node]-a[node])*(t-a["time"])/(b["time"]-a["time"])

    maxima = {}
    try:
        for probe in case["probes"]:
            error = abs(sample(probe["time"],probe.get("node","out"))-probe["expected"])
            maxima[probe["metric"]] = max(maxima.get(probe["metric"], 0), error)
            if error > probe["tolerance"]:
                failures.append(f"{probe['metric']} at {probe['time']:.9g}: {error:.6g} V exceeds {probe['tolerance']:.6g} V")
        local = {}
        for metric in case.get("metrics", []):
            actual = sample(metric["t2"],metric.get("node","out"))-sample(metric["t1"],metric.get("node","out"))
            local[metric["name"]] = actual
            if abs(actual-metric["expected"]) > metric["tolerance"]:
                failures.append(f"{metric['name']}: {actual:.9g} V instead of {metric['expected']:.9g} V")
        for event in case.get("crossings",[]):
            node=event.get("node","out");level=event["level"];direction=event["direction"]
            observed=[]
            for a,b in zip(rows,rows[1:]):
                av,bv=a[node]-level,b[node]-level
                if (direction>0 and av<0<=bv) or (direction<0 and av>0>=bv):
                    at=a["time"]+(b["time"]-a["time"])*(-av)/(bv-av)
                    if event["start"]<=at<=event["end"]:observed.append(at)
            wanted=event["expected_times"]
            local[event["name"]]=observed
            if len(observed)!=len(wanted) or any(abs(a-b)>event["tolerance"] for a,b in zip(observed,wanted)):
                failures.append(f"{event['name']} crossings {observed} instead of {wanted}")
    except (ValueError, KeyError) as exc:
        failures.append(str(exc))
        local = {}
    return dict(passed=not failures, failures=failures, max_error_V=maxima, local_metrics=local)
